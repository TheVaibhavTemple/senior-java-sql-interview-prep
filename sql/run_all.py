#!/usr/bin/env python3
"""Rebuild prep.db from 00-schema, run every '-- >>> QUERY' block in every .sql
   file, and stamp the real result set back into the file as a comment.

   Usage:  python3 run_all.py            # run everything and stamp
           python3 run_all.py --dry      # run everything, print failures only
"""
import glob, os, re, sqlite3, sys, textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
DB   = os.path.join(HERE, 'prep.db')
MARK = '-- ================= RESULTS'


def build_db():
    if os.path.exists(DB):
        os.remove(DB)
    con = sqlite3.connect(DB)
    con.isolation_level = None      # explicit BEGIN / ROLLBACK in S22 must work
    for f in ('01_schema.sql', '02_seed.sql'):
        con.executescript(open(os.path.join(HERE, '00-schema', f), encoding='utf-8').read())
    con.commit()
    return con


def render(cur, rows):
    if cur.description is None:
        return ['(no result set)']
    cols = [d[0] for d in cur.description]
    table = [cols] + [['NULL' if v is None else str(v) for v in r] for r in rows]
    width = [max(len(r[i]) for r in table) for i in range(len(cols))]
    out = ['  '.join(c.ljust(width[i]) for i, c in enumerate(cols)).rstrip(),
           '  '.join('-' * width[i] for i in range(len(cols)))]
    for r in table[1:]:
        out.append('  '.join(r[i].ljust(width[i]) for i in range(len(cols))).rstrip())
    out.append('(%d row%s)' % (len(rows), '' if len(rows) == 1 else 's'))
    return out


def main():
    dry = '--dry' in sys.argv
    files = sorted(glob.glob(os.path.join(HERE, '*', '*.sql')))
    files = [f for f in files if '00-schema' not in f]
    failures, queries = [], 0

    for path in files:
        con = build_db()          # fresh database per FILE: each file is reproducible alone
        src = open(path, encoding='utf-8').read()
        src = src.split('\n' + MARK)[0].rstrip() + '\n'       # drop any previous stamp
        blocks = re.findall(r'^-- >>> QUERY:?[ \t]*([^\n]*)\n(.*?)(?=^-- >>> QUERY|\Z)',
                            src, re.M | re.S)
        if not blocks:
            failures.append((os.path.basename(path), 'no QUERY block', ''))
            continue

        out = [MARK + ' ' + '=' * 72,
               '-- Generated by run_all.py against 00-schema/01_schema.sql + 02_seed.sql',
               '-- Engine: SQLite ' + sqlite3.sqlite_version
               + '.  Fresh database per file, so each file reproduces standalone.',
               '-- ' + '-' * 88]
        for label, sql in blocks:
            sql = sql.strip()
            if not sql:
                continue
            queries += 1
            out.append('-- [' + (label or 'query') + ']')
            try:
                cur = con.execute(sql)
                rows = cur.fetchall()
                for line in render(cur, rows):
                    out.append('--   ' + line)
            except Exception as exc:                              # noqa: BLE001
                failures.append((os.path.basename(path), label, str(exc)))
                out.append('--   ERROR: ' + str(exc))
            out.append('--')
        out.append('-- ' + '=' * 86)

        if not dry:
            open(path, 'w', encoding='utf-8').write(src + '\n' + '\n'.join(out) + '\n')

    print('files: %d   queries run: %d   failures: %d' % (len(files), queries, len(failures)))
    for name, label, err in failures:
        print('  !! %-46s [%s]  %s' % (name, label, err))
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
