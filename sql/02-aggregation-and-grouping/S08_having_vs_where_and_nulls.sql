-- ================================================================================================
-- S08  .  WHERE vs HAVING, and how NULL behaves in aggregates
-- ------------------------------------------------------------------------------------------------
-- TRACK        : Aggregation & Grouping
-- DIFFICULTY   : EASY    (1 of 3)
-- WEIGHTAGE    : HIGH    ***  asked in almost every round
-- TECHNIQUE    : Logical clause order; NULL semantics in comparisons and aggregates
--
-- PROBLEM
--   Explain the difference between WHERE and HAVING and prove it. Then explain what NULL does
--   to COUNT, AVG, comparisons and NOT IN.
--
-- ALGORITHM
--   1. The logical order is: FROM -> WHERE -> GROUP BY -> HAVING -> SELECT -> ORDER BY -> LIMIT.
--   2. WHERE filters ROWS before grouping, so it cannot see an aggregate.
--   3. HAVING filters GROUPS after aggregation, so it can.
--   4. A column alias defined in SELECT is not visible in WHERE or HAVING on most engines.
--   5. NULL is not a value: every comparison with it is UNKNOWN, and UNKNOWN is not TRUE.
--   6. COUNT(col) skips NULLs; COUNT(*) does not. AVG divides by the non-NULL count.
--
-- APPROACHES
--   APPROACH                                     VERDICT       NOTE
--   ---------------------------------------------------------------------------------------------
--   Filter rows in HAVING                        avoid         works, but kills index usage
--   Filter rows in WHERE, groups in HAVING       WRITE THIS    smallest input to the aggregation
--   x = NULL                                     avoid         always UNKNOWN; use IS NULL
--   NOT IN (list containing NULL)                avoid         returns no rows. See S23.
--
-- WHY THIS ONE
--   This is the warm-up question that decides how deep the rest of the interview goes. The
--   answer that lands is not the definition -- it is "WHERE runs before grouping so it shrinks
--   the input, which is also why it is the faster place to filter".
--
-- FOLLOW-UPS
--   ? Move a row filter from WHERE into HAVING -- same result, what changes in the plan?
--   ? Why does AVG(salary) ignore NULL rows instead of treating them as 0?
--   ? What does COUNT(dept_id) return when some rows have no department?
--   ? Why does ORDER BY see a SELECT alias when WHERE does not?
--
-- ALSO UNLOCKS
--   - COUNT(*) vs COUNT(col) vs COUNT(DISTINCT col)
--   - NULL handling with COALESCE and NULLIF
--   - Three-valued logic
--   - Why NOT IN with NULL returns nothing
-- ================================================================================================

-- >>> QUERY: WHERE filters rows, HAVING filters groups -- both in one query
SELECT d.dept_name, COUNT(*) AS seniors, ROUND(AVG(e.salary), 0) AS avg_senior_salary
FROM   employees e JOIN departments d ON d.dept_id = e.dept_id
WHERE  e.salary >= 90000           -- ROW filter: runs BEFORE grouping
GROUP  BY d.dept_id, d.dept_name
HAVING COUNT(*) >= 2               -- GROUP filter: runs AFTER aggregation
ORDER  BY d.dept_name;

-- >>> QUERY: NULL in comparisons -- every one of these is UNKNOWN, so nothing matches
SELECT (SELECT COUNT(*) FROM employees WHERE dept_id =  NULL) AS eq_null,
       (SELECT COUNT(*) FROM employees WHERE dept_id <> NULL) AS ne_null,
       (SELECT COUNT(*) FROM employees WHERE dept_id IS NULL) AS is_null;

-- >>> QUERY: NULL in aggregates
SELECT COUNT(*)                AS all_rows,
       COUNT(dept_id)          AS non_null_dept,
       COUNT(DISTINCT dept_id) AS distinct_depts,
       ROUND(AVG(salary), 0)   AS avg_salary,
       SUM(salary) / COUNT(*)  AS manual_avg_all_rows
FROM   employees;

-- >>> QUERY: the rows an INNER JOIN drops because dept_id is NULL
SELECT 'inner join' AS kind, COUNT(*) AS rows FROM employees e JOIN departments d ON d.dept_id = e.dept_id
UNION ALL
SELECT 'left join',  COUNT(*) FROM employees e LEFT JOIN departments d ON d.dept_id = e.dept_id
UNION ALL
SELECT 'employees',  COUNT(*) FROM employees;

-- >>> QUERY: COALESCE gives the NULL department a readable label
SELECT COALESCE(d.dept_name, '(unassigned)') AS dept, COUNT(*) AS headcount
FROM   employees e LEFT JOIN departments d ON d.dept_id = e.dept_id
GROUP  BY COALESCE(d.dept_name, '(unassigned)')
ORDER  BY headcount DESC, dept;

